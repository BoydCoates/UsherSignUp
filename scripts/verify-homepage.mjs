import { ConvexHttpClient } from 'convex/browser';
import { makeFunctionReference } from 'convex/server';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const client = new ConvexHttpClient('https://sleek-beagle-36.convex.cloud', { logger: false });
const ref = name => makeFunctionReference(name);
const initial = await client.query(ref('homepage:get'), {});
assert(initial.content.heroTitle);
await assert.rejects(client.mutation(ref('homepage:uploadUrl'), {}));
await assert.rejects(client.mutation(ref('homepage:save'), { content: initial.content, photoId: null, version: 0 }));
console.log('Public homepage read and anonymous write rejection verified.');
console.log('Ready for BoydCoates password on hidden stdin.');
process.stdin.setRawMode(true); process.stdin.resume();
const password = await new Promise(resolve => { let text = ''; const receive = chunk => { for (const character of chunk.toString()) { if (character === '\r' || character === '\n') { process.stdin.off('data', receive); process.stdin.setRawMode(false); process.stdin.pause(); resolve(text); return; } if (character === '\u0003') process.exit(1); text += character; } }; process.stdin.on('data', receive); });
const login = await client.action(ref('auth:signIn'), { provider: 'password', params: { email: 'BoydCoates', password, flow: 'signIn' } });
assert(login.tokens?.token);
client.setAuth(login.tokens.token);
const admin = await client.query(ref('admin:me'), {});
assert.equal(admin.username, 'BoydCoates');
const before = await client.query(ref('admin:dashboard'), {});
const templates = await client.query(ref('admin:templates'), {});
const page = await client.query(ref('homepage:edit'), {});
// Publish the existing/default content only; no test names or photos are published.
await client.mutation(ref('homepage:save'), { content: page.content, photoId: page.photoId, version: page.version });
assert.deepEqual((await client.query(ref('homepage:get'), {})).content, page.content);
const url = await client.mutation(ref('homepage:uploadUrl'), {});
const bytes = await readFile('my-website/public/utica-logo.jpeg');
const response = await fetch(url, { method: 'POST', headers: { 'Content-Type': 'image/jpeg' }, body: bytes });
assert(response.ok);
const { storageId } = await response.json();
await client.mutation(ref('homepage:discardUpload'), { photoId: storageId });
const after = await client.query(ref('admin:dashboard'), {});
assert.equal(before.length, after.length);
console.log(`Admin sign-in, publishing, image upload/cleanup, and existing dashboard verified (${after.length} schedules, ${templates.length} templates).`);
await client.action(ref('auth:signOut'), {});
client.clearAuth();
const schedule = await client.query(ref('public:schedule'), { publicId: '44d1c864-83ac-491b-8dab-758e303b858b' });
console.log(schedule ? 'Existing shared schedule still loads.' : 'Existing shared schedule endpoint responds; this link is not currently published.');
